mod common;

use std::collections::BTreeMap;
use std::sync::Arc;

use common::{TestRepo, revspec, snapshot};
use diffle::protocol::{EnterRequest, Snapshot};

fn batch_repo() -> TestRepo {
    let t = TestRepo::new();
    t.write("small.txt", "one\ntwo\n");
    // Large, textual, no generated marker: the sniff must not read it whole.
    t.write("big.txt", "x".repeat(200_000) + "\n");
    if cfg!(unix) {
        t.write("odd\nname.txt", "odd\n");
    }
    t.write("has space.txt", "sp\n");
    t.write("dir/in.txt", "in\n");
    t.commit("base");
    t.git(&["checkout", "-q", "-b", "feat"]);
    t.write("small.txt", "one\ntwo\nthree\n");
    t.write("gen.py", "# @generated by tool\nx = 1\n");
    t.commit("feat");
    t
}

fn generated(snap: &Snapshot) -> BTreeMap<&str, bool> {
    snap.changed.iter().map(|f| (f.path.as_str(), f.generated)).collect()
}

#[tokio::test]
async fn answers_a_list_of_blob_shas_from_one_process_keeping_only_a_prefix_of_each() {
    let t = batch_repo();
    let repo = Arc::new(t.open().await);
    let shas = [
        t.git(&["rev-parse", "HEAD:small.txt"]),
        t.git(&["rev-parse", "HEAD:big.txt"]),
        "0".repeat(40),
        t.git(&["rev-parse", "HEAD:dir"]),
    ];
    let heads = repo.blob_heads(&shas, 16).await.unwrap();
    assert_eq!(repo.cat_file_spawns(), 1);
    assert_eq!(heads[&shas[0]], b"one\ntwo\nthree\n");
    assert_eq!(heads[&shas[1]].len(), 16);
    // Missing objects and non-blobs (a tree) are left out rather than failing the batch.
    assert!(!heads.contains_key(&shas[2]) && !heads.contains_key(&shas[3]));
    // Concurrent readers share the process; answers stay matched to their names.
    let reads = (0..40).map(|i| {
        let repo = repo.clone();
        async move { repo.head("HEAD", if i % 2 == 1 { "small.txt" } else { "big.txt" }, 4).await.unwrap().unwrap() }
    });
    let many = futures::future::join_all(reads).await;
    for (i, body) in many.iter().enumerate() {
        assert_eq!(body, if i % 2 == 1 { b"one\n" } else { b"xxxx" });
    }
    assert_eq!(repo.cat_file_spawns(), 1);
}

#[tokio::test]
async fn show_reads_whole_blobs_through_one_process_and_reports_non_blobs_absent() {
    let t = batch_repo();
    let repo = Arc::new(t.open().await);
    let files = ["small.txt", "big.txt", "dir/in.txt"];
    let reads = (0..300).map(|i| {
        let repo = repo.clone();
        async move { repo.show("HEAD", files[i % 3]).await.unwrap().map(|b| b.len()) }
    });
    let sizes = futures::future::join_all(reads).await;
    for (i, size) in sizes.into_iter().enumerate() {
        assert_eq!(size, Some([14, 200_001, 3][i % 3]));
    }
    assert_eq!(repo.cat_file_spawns(), 1);
    assert!(repo.show("HEAD", "dir").await.unwrap().is_none());
    assert!(repo.show("HEAD", "nope.txt").await.unwrap().is_none());
    assert!(repo.show(&"0".repeat(40), "small.txt").await.unwrap().is_none());
    assert_eq!(repo.head("HEAD", "small.txt", 3).await.unwrap().unwrap(), b"one");
    assert!(repo.head("HEAD", "missing.txt", 10).await.unwrap().is_none());
    assert!(repo.head("HEAD", "dir", 10).await.unwrap().is_none());
}

#[tokio::test]
async fn reports_missing_names_with_spaces_without_stalling_the_batch() {
    let t = batch_repo();
    let repo = t.open().await;
    assert_eq!(repo.show("HEAD", "has space.txt").await.unwrap().unwrap(), b"sp\n");
    assert!(repo.show("HEAD", "no such.txt").await.unwrap().is_none());
    assert!(repo.head("HEAD", "also missing.txt", 4).await.unwrap().is_none());
    assert_eq!(repo.show("main", "small.txt").await.unwrap().unwrap(), b"one\ntwo\n");
    // A name with a newline cannot ride the batch, so both reads fall back to a plain cat-file.
    if cfg!(unix) {
        assert_eq!(repo.show("HEAD", "odd\nname.txt").await.unwrap().unwrap(), b"odd\n");
        assert_eq!(repo.head("HEAD", "odd\nname.txt", 100).await.unwrap().unwrap(), b"odd\n");
    }
}

#[tokio::test]
async fn reaps_an_idle_batch_and_respawns_on_the_next_request() {
    let t = batch_repo();
    let repo = t.open().await;
    assert!(repo.show("HEAD", "small.txt").await.unwrap().is_some());
    tokio::time::sleep(std::time::Duration::from_millis(2500)).await;
    assert!(repo.show("HEAD", "small.txt").await.unwrap().is_some());
    assert_eq!(repo.cat_file_spawns(), 2);
}

#[tokio::test]
async fn the_snapshot_resniffs_only_blobs_a_commit_changed() {
    let t = batch_repo();
    let repo = Arc::new(t.open().await);
    let (snapshotter, first) = snapshot(&repo, revspec(&["main..feat"])).await;
    assert_eq!(generated(&first), BTreeMap::from([("gen.py", true), ("small.txt", false)]));
    t.write("small.txt", "# DO NOT EDIT\nfour\n");
    t.git(&["commit", "-q", "-am", "more"]);
    snapshotter.invalidate(2);
    let second = snapshotter.current().await.unwrap();
    assert_eq!(generated(&second), BTreeMap::from([("gen.py", true), ("small.txt", true)]));
}

#[tokio::test]
async fn the_working_snapshot_sniffs_uncommitted_files_from_the_worktree() {
    let t = batch_repo();
    t.write("gen2.py", "# @generated by tool\nx = 1\n");
    t.write("plain.py", "x = 1\n");
    let repo = Arc::new(t.open().await);
    let (_, snap) = snapshot(&repo, EnterRequest::Working).await;
    assert_eq!(generated(&snap), BTreeMap::from([("gen2.py", true), ("plain.py", false)]));
}
