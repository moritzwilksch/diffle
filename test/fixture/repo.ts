/**
 * `source` with each `from` replaced once, in order. A `from` that no longer occurs is a
 * mistake in this file, so it throws instead of leaving the version silently unchanged.
 */
function edit(source: string, ...changes: [from: string, to: string][]): string {
  for (const [from, to] of changes) {
    if (!source.includes(from)) throw new Error(`fixture edit: text not found:\n${from}`);
    source = source.replace(from, to);
  }
  return source;
}

