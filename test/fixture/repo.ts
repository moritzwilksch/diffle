export interface FixtureRepo {
  dir: string;
  /** Commit hashes by branch and tag name; stable across machines. */
  refs: Record<string, string>;
}

/** No user config, no hooks, no line-ending conversion: only this file decides what gets hashed. */
const GIT_ARGS = [
  '-c',
  'core.autocrlf=false',
  '-c',
  'core.safecrlf=false',
  '-c',
  'core.quotepath=false',
  '-c',
  'commit.gpgsign=false',
  '-c',
  'tag.gpgsign=false',
];

/** Build the fixture repository in `dir`, replacing whatever is there. */
export async function buildFixtureRepo(dir: string): Promise<FixtureRepo> {
  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });

  let commits = 0;
  const git = (args: string[], author: Author = 'ada'): string => {
    const date = new Date(EPOCH + commits * 3_600_000).toISOString();
    const who = AUTHORS[author];
    return execFileSync('git', [...GIT_ARGS, ...args], {
      cwd: dir,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      env: {
        ...process.env,
        GIT_CONFIG_GLOBAL: '/dev/null',
        GIT_CONFIG_NOSYSTEM: '1',
        GIT_AUTHOR_NAME: who.name,
        GIT_AUTHOR_EMAIL: who.email,
        GIT_COMMITTER_NAME: who.name,
        GIT_COMMITTER_EMAIL: who.email,
        GIT_AUTHOR_DATE: date,
        GIT_COMMITTER_DATE: date,
      },
    }).trim();
  };

  const write = async (files: Files) => {
    for (const [path, content] of Object.entries(files)) {
      const target = join(dir, path);
      if (content === null) {
        await rm(target);
      } else {
        await mkdir(dirname(target), { recursive: true });
        await writeFile(target, content);
      }
    }
  };

  // `--template=` skips the sample hooks, which are noise in a fixture and differ between Git builds.
  git(['init', '-q', '-b', MAIN_BRANCH, '--template=']);

  for (const commit of HISTORY) {
    if (commit.checkout) git(['checkout', '-q', commit.checkout]);
    if (commit.branch) git(['checkout', '-q', '-b', commit.branch]);
    for (const [from, to] of commit.moves ?? []) {
      await mkdir(dirname(join(dir, to)), { recursive: true });
      git(['mv', from, to]);
    }
    await write(commit.files ?? {});
    git(['add', '-A']);
    for (const path of commit.exec ?? []) {
      // The index bit is what gets committed; the chmod only makes the checkout runnable on POSIX.
      git(['update-index', '--chmod=+x', path]);
      if (process.platform !== 'win32') await chmod(join(dir, path), 0o755);
    }
    git(['commit', '-q', '-m', commit.message], commit.author);
    if (commit.tag) git(['tag', '-a', commit.tag, '-m', `tally ${commit.tag.slice(1)}`], commit.author);
    commits++;
  }

  await write(WORKTREE.staged);
  git(['add', ...Object.keys(WORKTREE.staged)]);
  await write(WORKTREE.unstaged);
  await write(WORKTREE.untracked);

  const refs: Record<string, string> = {};
  for (const ref of [MAIN_BRANCH, FEATURE_BRANCH, TAG]) refs[ref] = git(['rev-parse', `${ref}^{commit}`]);
  return { dir, refs };
}
